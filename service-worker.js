// Service worker — Jurnal Sastra Rumah Bamboe
// Menyimpan "app shell" (HTML/CSS/JS/ikon) agar aplikasi tetap terbuka saat offline.
// Data tulisan sendiri diambil live dari Blogger saat online, dan disimpan
// sebagian di localStorage oleh app.js untuk ditampilkan saat offline.

const CACHE_NAME = "srb-shell-v1";
const APP_SHELL = [
  "./",
  "./index.html",
  "./style.css",
  "./app.js",
  "./manifest.json",
  "./icons/icon-192.png",
  "./icons/icon-512.png",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL))
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))
      )
    )
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  const { request } = event;

  // Jangan mencampuri permintaan ke Blogger (feed data) atau domain lain —
  // biarkan itu selalu live agar tulisan terbaru selalu tampil saat online.
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          return response;
        })
        .catch(() => caches.match("./index.html"));
    })
  );
});
